param([Parameter(Mandatory=$true)][string]$SnapshotDirectory)
$ErrorActionPreference = 'Stop'
# Migawki z CUTTIME_UI_DIR po tests/http.php; tylko osobny katalog TEMP.
$name = Split-Path $SnapshotDirectory -Leaf
if ($name -notmatch '^cuttime-ux-[a-f0-9]{16}$') {
    throw 'Use the isolated cuttime-ux-* directory generated by HTTP tests.'
}
# Buduj ścieżkę wyłącznie pod TEMP; uwzględnia też aliasy Windows 8.3.
$snapshot = (Resolve-Path -LiteralPath (Join-Path ([IO.Path]::GetTempPath()) $name)).Path
$edge = 'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe'
if (!(Test-Path -LiteralPath $edge)) { throw 'Microsoft Edge is required for this optional browser check.' }
$pageNames = Get-Content -LiteralPath (Join-Path $snapshot 'pages.json') -Raw | ConvertFrom-Json
foreach ($name in $pageNames) { if ($name -notmatch '^[a-z-]+$') { throw 'Invalid snapshot name.' } }
$pageJson = ConvertTo-Json -InputObject @($pageNames) -Compress
$template = @'
<!doctype html><html><head><meta charset="utf-8"><title>CutTime responsive checks</title></head><body>
<pre id="report">Running</pre><script>
(async () => {
 const pages = __PAGES__;
 const results = [];
 for (const width of [320, 375, 768]) {
  for (const page of pages) {
   const frame = document.createElement('iframe');
   frame.style.cssText = `display:block;border:0;width:${width}px;height:900px`;
   const ready = new Promise(resolve => frame.onload = resolve);
   frame.src = page + '.html'; document.body.append(frame); await ready;
   const doc = frame.contentDocument; await doc.fonts.ready;
   const viewport = doc.documentElement.clientWidth;
   const overflow = Math.max(doc.documentElement.scrollWidth, doc.body.scrollWidth) > viewport + 1;
   const unnamed = [...doc.querySelectorAll('input:not([type=hidden]),select,textarea')].filter(el => !el.labels?.length && !el.getAttribute('aria-label')).length;
   results.push({page, width, viewport, scrollWidth:doc.documentElement.scrollWidth, overflow, unnamed});
   frame.remove();
  }
 }
 document.getElementById('report').textContent = JSON.stringify(results);
 document.title = results.every(r => !r.overflow && !r.unnamed) ? 'PASS' : 'FAIL';
})().catch(e => document.getElementById('report').textContent = 'ERROR: ' + e.message);
</script></body></html>
'@
Set-Content -LiteralPath (Join-Path $snapshot 'responsive.html') -Encoding UTF8 -Value $template.Replace('__PAGES__', $pageJson)
$profile = Join-Path $snapshot 'edge-profile'
$dom = Join-Path $snapshot 'responsive-dom.html'
$uri = ([uri](Join-Path $snapshot 'responsive.html')).AbsoluteUri
$arguments = @('--headless', '--disable-gpu', '--no-first-run', '--allow-file-access-from-files', ('--user-data-dir="' + $profile + '"'), '--virtual-time-budget=15000', '--dump-dom', $uri)
$browser = Start-Process -FilePath $edge -ArgumentList $arguments -WindowStyle Hidden -PassThru -RedirectStandardOutput $dom -RedirectStandardError (Join-Path $snapshot 'edge.log')
if (!$browser.WaitForExit(45000)) { Stop-Process -Id $browser.Id; throw 'Browser check timed out.' }
$html = Get-Content -LiteralPath $dom -Raw
if ([string]::IsNullOrWhiteSpace($html)) { throw 'Browser returned no DOM. Check edge.log and permission to run Edge headless.' }
$match = [regex]::Match($html, '<pre id="report">(.*?)</pre>', 'Singleline')
if (!$match.Success) { throw 'Browser did not return a layout report.' }
$report = [Net.WebUtility]::HtmlDecode($match.Groups[1].Value) | ConvertFrom-Json
$report | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $snapshot 'responsive-results.json') -Encoding UTF8
$failures = @($report | Where-Object { $_.overflow -or $_.unnamed })
Write-Output ('Browser layout checks: ' + @($report).Count + '; failures: ' + $failures.Count)
$failures | Format-Table
if ($failures.Count -gt 0) { exit 1 }
# Podgląd całego podsumowania w ramce o szerokości telefonu.
$preview = '<!doctype html><html><head><meta charset="utf-8"></head><body style="margin:0;background:#eee"><iframe title="Podsumowanie wizyty, 320px" src="summary.html" style="border:0;width:320px;height:2200px"></iframe></body></html>'
Set-Content -LiteralPath (Join-Path $snapshot 'preview.html') -Value $preview -Encoding UTF8
$previewUri = ([uri](Join-Path $snapshot 'preview.html')).AbsoluteUri
$arguments = @('--headless', '--disable-gpu', '--no-first-run', '--allow-file-access-from-files', ('--user-data-dir="' + $profile + '"'), '--window-size=420,2200', '--virtual-time-budget=3000', ('--screenshot="' + (Join-Path $snapshot 'summary-mobile.png') + '"'), $previewUri)
$browser = Start-Process -FilePath $edge -ArgumentList $arguments -WindowStyle Hidden -PassThru -RedirectStandardError (Join-Path $snapshot 'edge-preview.log')
if (!$browser.WaitForExit(30000)) { Stop-Process -Id $browser.Id; throw 'Screenshot timed out.' }
